import * as React from "react";
import { createFileRoute } from "@tanstack/react-router";
import {
  Award,
  CheckCircle2,
  Flame,
  Loader2,
  RefreshCw,
  ShieldAlert,
  ShieldCheck,
  Sparkles,
  XCircle,
} from "lucide-react";

import { useWebMCP } from "use-webmcp-tool";

import { runWebMCPTool } from "@/lib/webmcp-telemetry";

import { useLanguage } from "@/components/language-provider";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { usePracticeStreak } from "@/hooks/use-practice-streak";
import { FALLBACK_PRACTICE } from "@/lib/local-analyzer";
import { callMcpTool } from "@/lib/mcp-client";
import type { PracticeItem } from "@/lib/types";
import { cn } from "@/lib/utils";

export const Route = createFileRoute("/practice")({
  component: PracticePage,
});

function friendlyErrorMessage(error: unknown, genericError: string): string {
  const message = error instanceof Error ? error.message : String(error);
  return message.replace(/^[A-Z_]+:\s*/, "") || genericError;
}

function PracticePage() {
  const { t, tf } = useLanguage();
  // Start with the built-in round so a visit never spends AI credits; AI rounds are on request.
  const [items, setItems] = React.useState<PracticeItem[] | null>(FALLBACK_PRACTICE);
  const [starter, setStarter] = React.useState(true);
  const [loading, setLoading] = React.useState(false);
  const [error, setError] = React.useState<string | null>(null);
  const [answers, setAnswers] = React.useState<Record<number, boolean>>({});
  const [index, setIndex] = React.useState(0);
  const [offline, setOffline] = React.useState(false);

  // Rounds are generated by the MCP server's get_practice_round tool (the same
  // tool an external agent would call), not fetched through a separate path.
  const loadRound = React.useCallback(async () => {
    setLoading(true);
    setError(null);
    setAnswers({});
    setIndex(0);
    try {
      const { structured } = await callMcpTool<{ items: PracticeItem[]; offline: boolean }>(
        "get_practice_round",
      );
      if (!structured?.items?.length) throw new Error("No practice items returned.");
      setItems(structured.items);
      setOffline(structured.offline);
      setStarter(false);
    } catch (err) {
      // Keep the game playable even if the MCP call itself fails (network, cold start, etc.).
      setItems(FALLBACK_PRACTICE);
      setOffline(true);
      setStarter(false);
      void err;
    } finally {
      setLoading(false);
    }
  }, []);

  const current = items?.[index];
  const answered = current ? answers[index] !== undefined : false;
  const score = Object.entries(answers).filter(
    ([i, guess]) => guess === items?.[Number(i)]?.isScam,
  ).length;

  const guess = (isScam: boolean) => {
    if (answered) return;
    setAnswers((prev) => ({ ...prev, [index]: isScam }));
  };

  const next = () => {
    if (!items) return;
    setIndex((i) => Math.min(i + 1, items.length - 1));
  };

  const roundDone = items != null && Object.keys(answers).length === items.length;

  const streak = usePracticeStreak();
  const recordedRoundRef = React.useRef(false);
  React.useEffect(() => {
    recordedRoundRef.current = false;
  }, [items]);
  React.useEffect(() => {
    if (roundDone && !recordedRoundRef.current) {
      recordedRoundRef.current = true;
      streak.recordRound(score);
    }
  }, [roundDone, score, streak]);

  useWebMCP<{ is_scam: boolean }>({
    name: "answer_practice_question",
    description:
      "Answers the current message in ScamShield BD's Scam Spotter practice game, guessing whether it's a scam or genuine, and returns whether the guess was correct plus the explanation and red flags.",
    inputSchema: {
      type: "object",
      properties: {
        is_scam: { type: "boolean", description: "True to guess 'scam', false to guess 'genuine'" },
      },
      required: ["is_scam"],
    },
    enabled: !!current && !answered,
    execute: ({ is_scam }) =>
      runWebMCPTool("answer_practice_question", () => {
        if (!current) throw new Error("No practice message is loaded right now.");
        guess(is_scam);
        const correct = is_scam === current.isScam;
        const flags = current.redFlags.length ? `\nRed flags: ${current.redFlags.join("; ")}` : "";
        return `${correct ? "Correct" : "Not quite"} — this message is ${current.isScam ? "a scam" : "genuine"}. ${current.explanation}${flags}`;
      }),
  });

  useWebMCP({
    name: "next_practice_message",
    description: "Advances to the next message in the current Scam Spotter practice round.",
    inputSchema: { type: "object", properties: {} },
    enabled: answered && !roundDone,
    execute: () =>
      runWebMCPTool("next_practice_message", () => {
        next();
        return "Moved to the next practice message.";
      }),
  });

  return (
    <>
      <section className="mx-auto w-full max-w-2xl px-4 py-10 sm:py-14">
        <h1 className="text-2xl font-bold tracking-tight sm:text-3xl">{t("practice.title")}</h1>
        <p className="mt-2 text-muted-foreground">{t("practice.subtitle")}</p>

        {streak.hydrated && (streak.current > 0 || streak.correctTotal > 0) ? (
          <div className="mt-4 flex flex-wrap items-center gap-2 text-sm">
            <Badge variant="outline" className="gap-1.5">
              <Flame className="size-3.5 text-suspicious" aria-hidden="true" />
              {tf("practice.streakDays", { count: streak.current })}
            </Badge>
            {streak.earnedBadges.map((b) => (
              <Badge key={b.id} variant="secondary" className="gap-1.5">
                <Award className="size-3.5" aria-hidden="true" />
                {t(`practice.badge.${b.id}`)}
              </Badge>
            ))}
          </div>
        ) : null}

        {loading ? (
          <div className="mt-10 flex flex-col items-center gap-3 py-16 text-muted-foreground">
            <Loader2 className="size-6 animate-spin" aria-hidden="true" />
            <p>{t("practice.generating")}</p>
          </div>
        ) : error ? (
          <div className="mt-10 rounded-lg border border-destructive/50 bg-destructive/5 p-4 text-sm text-destructive">
            <p>{error}</p>
            <Button
              type="button"
              variant="outline"
              className="mt-3"
              onClick={() => void loadRound()}
            >
              {t("practice.tryAgain")}
            </Button>
          </div>
        ) : items && current ? (
          <div className="mt-6 space-y-5">
            {offline || starter ? (
              <div className="flex flex-col gap-3 rounded-lg border border-border bg-muted p-3 text-sm text-muted-foreground sm:flex-row sm:items-center sm:justify-between">
                <p>{t(offline ? "practice.offlineNotice" : "practice.starterNotice")}</p>
                <Button
                  type="button"
                  variant="outline"
                  size="sm"
                  className="shrink-0"
                  onClick={() => void loadRound()}
                >
                  <Sparkles className="size-4" aria-hidden="true" />
                  {t("practice.newAiRound")}
                </Button>
              </div>
            ) : null}
            <div
              className="flex items-center justify-between text-sm text-muted-foreground"
              aria-live="polite"
            >
              <span>{tf("practice.messageOf", { current: index + 1, total: items.length })}</span>
              <span>{tf("practice.score", { score, answered: Object.keys(answers).length })}</span>
            </div>

            <Card>
              <CardContent className="pt-6 text-base leading-relaxed">
                {current.message}
              </CardContent>
            </Card>

            {!answered ? (
              <div className="grid grid-cols-2 gap-3">
                <Button
                  type="button"
                  variant="outline"
                  size="lg"
                  className="border-danger/40 hover:border-danger hover:bg-danger/10"
                  onClick={() => guess(true)}
                >
                  <ShieldAlert className="size-4" aria-hidden="true" />
                  {t("practice.scam")}
                </Button>
                <Button
                  type="button"
                  variant="outline"
                  size="lg"
                  className="border-safe/40 hover:border-safe hover:bg-safe/10"
                  onClick={() => guess(false)}
                >
                  <ShieldCheck className="size-4" aria-hidden="true" />
                  {t("practice.genuine")}
                </Button>
              </div>
            ) : (
              <Card
                className={cn(
                  "border-2",
                  answers[index] === current.isScam ? "border-safe" : "border-danger",
                )}
              >
                <CardHeader>
                  <div className="flex items-center gap-2">
                    {answers[index] === current.isScam ? (
                      <CheckCircle2 className="size-5 text-safe" aria-hidden="true" />
                    ) : (
                      <XCircle className="size-5 text-danger" aria-hidden="true" />
                    )}
                    <CardTitle className="text-base">
                      {answers[index] === current.isScam ? t("practice.correct") : t("practice.notQuite")}
                    </CardTitle>
                    <Badge variant={current.isScam ? "scam" : "safe"} className="ml-auto">
                      {current.isScam ? t("practice.scam") : t("practice.genuine")}
                    </Badge>
                  </div>
                </CardHeader>
                <CardContent className="space-y-3">
                  <p className="text-sm text-muted-foreground">{current.explanation}</p>
                  {current.redFlags.length > 0 ? (
                    <ul className="list-inside list-disc space-y-1 text-sm">
                      {current.redFlags.map((flag, i) => (
                        <li key={i}>{flag}</li>
                      ))}
                    </ul>
                  ) : null}
                </CardContent>
              </Card>
            )}

            {answered && !roundDone ? (
              <Button type="button" size="lg" className="w-full" onClick={next}>
                {t("practice.nextMessage")}
              </Button>
            ) : null}

            {roundDone ? (
              <div className="rounded-lg border border-border bg-card p-5 text-center">
                <p className="text-lg font-semibold">
                  {tf("practice.roundFinished", { score, total: items.length })}
                </p>
                <Button type="button" className="mt-4" onClick={() => void loadRound()}>
                  <RefreshCw className="size-4" aria-hidden="true" />
                  {t("practice.playAgain")}
                </Button>
              </div>
            ) : null}
          </div>
        ) : null}
      </section>
    </>
  );
}
